; Great Battle Gaiden 2 English patch. Applied by tools/build.py to a 2 MB copy (banks $28-$3F are free, 0xFF).
; Text engine notes: docs/re/text.md.
lorom

!BODY_BANK = $0028              ; must match tools/build.py BODY_BANK / BODY_TABLE
!BODY_TABLE = $8000
!CODE = $3F8000                 ; patch code, last bank of the 2 MB image

; ---------------------------------------------------------------------------------------------------------------
; Message bodies move to bank $28: the body pointer table ($1A:C1EC) is rebuilt at $28:8000 by the build.
; Both readers (page-clear pre-pass and the main printer) load the table address + bank as immediates.
org $01850B
    db $A9 : dw !BODY_TABLE     ; lda #table
org $018510
    db $A9 : dw !BODY_BANK      ; lda #bank
org $0186A2
    db $A9 : dw !BODY_TABLE
org $0186A7
    db $A9 : dw !BODY_BANK

; ---------------------------------------------------------------------------------------------------------------
; Line pitch 1 row instead of 2: Japanese needed a row above each line for dakuten; English doesn't, so a
; 2-line box holds 4 lines. Headers start one row higher (build.py), and the encoder adds a leading {n} plus
; blank rows between lines when the page fits the original 2-row spacing.
org $01855F
    db $69 : dw $0020           ; pre-pass newline: adc #$20 (was #$40)
org $0186D4
    db $69 : dw $0020           ; printer newline: adc #$20 (was #$40)
org $018594
    db $E9 : dw $0000           ; pre-pass cleared the dakuten row above each line (sbc #$20): with the first
                                ; line on that row it would wipe the box border, so clear the line row only

; ---------------------------------------------------------------------------------------------------------------
; The page-clear pre-pass counted control bytes as characters, so a line with {wait:XX} cleared tiles past its
; end (over the box border once English fills the width). Count printable bytes only. A = byte + 3 here.
org $01854C
    jml prepass_count

incsrc "../build/en_chars.asm"   ; 'A' = $21 ... generated by tools/build.py from its English table

; ---------------------------------------------------------------------------------------------------------------
; Stall item names ($01:8A3C): 16-byte records, 8 tiles top row (JP dakuten) + 8 tiles bottom row (name).
; English uses both rows for two-word names.
org $0193AE
    db "Cotton  ", "Candy   "
    db "        ", "Takoyaki"
    db "Flower  ", "Hat     "
    db "        ", "Corn    "
    db "        ", "Yo-yo   "
    db "        ", "Special "
    db "Ground  ", "Spinner "
    db "        ", "Balloon "
    db "        ", "Ramune  "
    db "        ", "Ramune  "
    db "        ", "Roar    "
    db "        ", "Great   "
    db "        ", "Stamen  "
    db "        ", "RX      "

; ---------------------------------------------------------------------------------------------------------------
; Game over / continue screen ($0B:AB6C, $0B:AD13): fixed-length rows via $0B:AF2E (A = length, X = source,
; Y = BG3 VRAM). The two clearing writes (old dakuten row, Continue row) now read zeros at $0B:8330.
!ZEROS = $8330
org $0BAB72 : dw go_continue
org $0BAB75 : dw 9
org $0BAB78 : dw $59CB              ; row 14, centred
org $0BAD1B : dw 22
org $0BAD1E : dw go_line1
org $0BAD21 : dw $5965              ; row 11, col 5
org $0BAD31 : dw !ZEROS             ; row 12 (was the dakuten row)
org $0BAD41 : dw 15
org $0BAD44 : dw go_line2
org $0BAD47 : dw $59AC              ; row 13, right edge under line 1
org $0BAD57 : dw !ZEROS             ; clear the Continue row (12 tiles)

org $0BE211                         ; the old strings, $E211-$E243
go_continue: db "Continue?"
go_line1: db "Don't give up! GO! GO!"
go_line2: db "Compati Heroes!"
warnpc $0BE244

; ---------------------------------------------------------------------------------------------------------------
; Shop "sold out" (うりきれ, 5 tiles): SOLD OUT takes 8 tiles. $19:BEA0 is the writer for cards 1-3 (Y = old left
; column, the caller's LDY is unchanged: shifted two tiles left here); card 4 has its own copy at $19:BE0F.
org $19BEA0
    jsl soldout_cards : rts
org $19BE0F
    rep #$30 : ldy #$5A90 : jsl soldout : jml $19BE3D

org !CODE
soldout_cards:
    rep #$30
    dey : dey
soldout:                        ; Y = BG3 VRAM word address of the first tile
    lda #$0008 : sta $00
    ldx #$0000
    jsl $00FF57                 ; open a VRAM write record: A = tiles, Y = address; returns Y = buffer index
-   lda.l soldtext,x : sta $00C0,y
    inx : inx : iny : iny
    dec $00 : bne -
    jsl $00FF5A
    rtl
soldtext: db "S",$20,"O",$20,"L",$20,"D",$20," ",$20,"O",$20,"U",$20,"T",$20

prepass_count:
    cmp #$FC                    ; byte < $F9: a character
    bcc .char
    cmp #$FF                    ; byte $FC {wait:XX}: also skip its argument
    bne .done
    rep #$20
    inc $18
    sep #$20
    bra .done
.char:
    inc $1A
.done:
    jml $018538
